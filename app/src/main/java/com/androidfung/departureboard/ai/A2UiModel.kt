package com.androidfung.departureboard.ai

import com.androidfung.departureboard.data.model.Departure
import com.androidfung.departureboard.data.model.Station

/**
 * Severity indicator for transit alerts and status banners in A2UI.
 */
enum class A2UiSeverity {
    INFO,
    GOOD_SERVICE,
    WARNING,
    DISRUPTION
}

/**
 * Interactive or executable action triggered by the AI assistant or commuter.
 */
sealed interface A2UiAction {
    data class OpenGoogleMaps(val origin: String, val destination: String) : A2UiAction
    data class OpenTflJourneyPlanner(val origin: String, val destination: String) : A2UiAction
    data class TrackTrain(val departure: Departure) : A2UiAction
    data class PinStation(val station: Station) : A2UiAction
    data class QueryPrompt(val text: String) : A2UiAction
}

/**
 * Declarative component blocks generated by the AI (Agent-to-UI).
 * The UI renders these as rich native Compose elements rather than pure unstructured text.
 */
sealed interface A2UiBlock {

    /**
     * Top-level summary message or contextual conversational response.
     */
    data class TextSummary(
        val message: String
    ) : A2UiBlock

    /**
     * Line status or disruption card (e.g., Elizabeth line severe delays, Central line good service).
     */
    data class LineStatusBanner(
        val lineName: String,
        val statusDescription: String,
        val reason: String? = null,
        val severity: A2UiSeverity = A2UiSeverity.INFO
    ) : A2UiBlock

    /**
     * Interactive live departure card showing upcoming trains/buses for a specific station.
     */
    data class LiveDeparturesCard(
        val station: Station,
        val departures: List<Departure>
    ) : A2UiBlock

    /**
     * Group of quick action buttons (e.g., Maps directions, tracking, suggested follow-ups).
     */
    data class ActionButtons(
        val actions: List<A2UiAction>
    ) : A2UiBlock
}

/**
 * Enriched A2UI payload returned by the Transit AI Assistant.
 */
data class A2UiResponse(
    val blocks: List<A2UiBlock>
)
